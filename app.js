function themeFor(data) {
  const rule = JOURNAL_THEME_RULES.find((entry) => entry.match(data));
  const spec = rule
    ? typeof rule.theme === "function"
      ? rule.theme(data)
      : rule.theme
    : null;
  const base = spec ? { ...DEFAULT_THEME, ...spec } : { ...DEFAULT_THEME };
  const label =
    base.label ||
    (data.container || data.publisher || "Journal").slice(0, 32);
  return { ...base, label };
}

function cardStyle(theme) {
  const titleFallback =
    theme.titleFallback || "Georgia, Times New Roman, serif";
  const bodyFallback =
    theme.bodyFallback || "system-ui, -apple-system, sans-serif";
  const vars = [
    `--badge:${theme.color}`,
    `--accent:${theme.color}`,
    `--title-font:'${theme.titleFont}',${titleFallback}`,
    `--body-font:'${theme.bodyFont}',${bodyFallback}`,
    `--title-weight:${theme.titleWeight}`,
    `--title-spacing:${theme.titleSpacing}`,
    `--fs-scale:${custom.scale / 100}`,
    `--card-w:${custom.width}px`,
  ];
  if (theme.metaFont) vars.push(`--meta-font:'${theme.metaFont}',${bodyFallback}`);
  if (theme.titleColor) vars.push(`--title-color:${theme.titleColor}`);
  if (theme.textColor) vars.push(`--text-color:${theme.textColor}`);
  if (theme.metaColor) vars.push(`--meta-color:${theme.metaColor}`);
  if (theme.rule) vars.push(`--rule:${theme.rule}`);
  if (theme.ruleWidth) vars.push(`--rule-w:${theme.ruleWidth}`);
  if (theme.topbar) vars.push(`--topbar:${theme.topbar}`);
  if (theme.topbarHeight != null) vars.push(`--topbar-h:${theme.topbarHeight}`);
  if (theme.logoHeight) vars.push(`--logo-h:${theme.logoHeight}`);
  if (custom.ratio !== "auto") vars.push(`--ratio:${custom.ratio}`);
  return vars.join(";");
}

function fontCacheKey(theme) {
  if (theme.googleFonts != null) return theme.googleFonts || "system";
  return uniq([theme.titleFont, theme.bodyFont].filter(Boolean)).join("|");
}

function googleFontsQuery(theme) {
  if (theme.googleFonts != null) return theme.googleFonts;
  return uniq([theme.titleFont, theme.bodyFont].filter(Boolean))
    .map((family) => `family=${encodeURIComponent(family)}:wght@400;600;700;800`)
    .join("&");
}

// Self-hosted faces (declared in style.css via @font-face) just need
// FontFaceSet to pull them in; Google-hosted families get a stylesheet link.
function loadLocalFonts(theme) {
  if (!theme.localFonts || !document.fonts) return Promise.resolve();
  return Promise.all(
    theme.localFonts.flatMap((family) => [
      document.fonts.load(`400 1em '${family}'`),
      document.fonts.load(`700 1em '${family}'`),
    ])
  ).catch(() => undefined);
}

function ensureFonts(theme) {
  const local = loadLocalFonts(theme);
  const key = fontCacheKey(theme);
  const query = googleFontsQuery(theme);
  if (loadedFontSets.has(key) || !query) {
    loadedFontSets.add(key);
    const ready = document.fonts && document.fonts.ready
      ? document.fonts.ready.catch(() => undefined)
      : Promise.resolve();
    return Promise.all([local, ready]);
  }
  loadedFontSets.add(key);
  const linked = new Promise((resolve) => {
    const link = document.createElement("link");
    link.rel = "stylesheet";
    // crossorigin lets html-to-image read cssRules and embed the fonts at export
    link.crossOrigin = "anonymous";
    link.href = `https://fonts.googleapis.com/css2?${query}&display=swap`;
    const done = () => {
      const ready = document.fonts && document.fonts.ready
        ? document.fonts.ready.catch(() => undefined)
        : Promise.resolve();
      ready.then(resolve);
    };
    link.onload = done;
    link.onerror = () => resolve();
    document.head.appendChild(link);
    setTimeout(done, 500);
  });
  return Promise.all([local, linked]);
}

/* ---------- Render ---------- */
// Toggleable fields. `title` is mandatory (always in the shot).
const FIELD_DEFS = [
  { key: "authors", label: "Authors", has: (d) => (d.authors || []).length > 0 },
  { key: "affiliations", label: "Affiliations", has: (d) => (d.affiliations || []).length > 0 },
  { key: "meta", label: "Journal & date", has: (d) => !!(d.container || d.type || d.date || d.publisher) },
  { key: "abstract", label: "Abstract", has: (d) => !!d.abstract },
  { key: "doi", label: "DOI", has: (d) => !!d.doi },
];

let currentData = null;
const fieldOn = {}; // key -> boolean

// Appearance controls (font size %, card width px, aspect ratio, journal vs
// minimal styling, export pixel ratio).
const custom = {
  scale: 100,
  width: 760,
  ratio: "auto",
  style: "journal",
  pixelRatio: 2,
};

function activeTheme(data) {
  if (custom.style === "minimal") {
    const label = (data.container || data.publisher || "Journal").slice(0, 32);
    return { ...DEFAULT_THEME, label };
  }
  return themeFor(data);
}

function mastheadHtml(theme) {
  if (theme.kind !== "branded") {
    return `<span class="badge">${esc(theme.label)}</span>`;
  }
  const bits = [];
  if (theme.logo)
    bits.push(`<img src="${esc(theme.logo)}" alt="${esc(theme.label)}" crossorigin="anonymous">`);
  if (theme.wordmark)
    bits.push(`<span class="jname-word">${esc(theme.wordmark)}</span>`);
  if (theme.journalName)
    bits.push(`<span class="jname">${esc(theme.journalName)}</span>`);
  return `<div class="masthead-row">${bits.join("")}</div>`;
}

function buildCardHtml(data) {
  const theme = activeTheme(data);
  const parts = [mastheadHtml(theme)];
  parts.push(`<h2 class="title">${esc(data.title)}</h2>`);

  if (fieldOn.authors)
    parts.push(
      `<p class="authors">${formatAuthors(data.authors) || "<span class='more'>Authors unavailable</span>"}</p>`
    );

  if (fieldOn.affiliations && (data.affiliations || []).length) {
    const CAP = 6;
    const affs = data.affiliations.slice(0, CAP).map(esc).join(" · ");
    const more = data.affiliations.length > CAP ? ` <span class="more">+ ${data.affiliations.length - CAP} more</span>` : "";
    parts.push(`<p class="affils">${affs}${more}</p>`);
  }

  if (fieldOn.meta) {
    const metaBits = [];
    if (data.container && data.container !== theme.label) metaBits.push(`<span><b>${esc(data.container)}</b></span>`);
    if (data.type) metaBits.push(`<span>${esc(data.type)}</span>`);
    if (data.date) metaBits.push(`<span>${esc(data.date)}</span>`);
    if (data.publisher && data.publisher !== theme.label && !data.container) metaBits.push(`<span>${esc(data.publisher)}</span>`);
    if (metaBits.length) parts.push(`<div class="meta">${metaBits.join("")}</div>`);
  }

  if (fieldOn.abstract && data.abstract)
    parts.push(`<p class="abstract">${esc(data.abstract)}</p>`);

  if (fieldOn.doi)
    parts.push(
      `<div class="doi"><a href="${esc(data.url)}" target="_blank" rel="noopener">doi.org/${esc(data.doi)}</a><span class="mark">${DOISHOT_MARK}</span></div>`
    );
  else
    parts.push(`<div class="doi end"><span class="mark">${DOISHOT_MARK}</span></div>`);

  const ratioClass = custom.ratio !== "auto" ? " ratio-fixed" : "";
  return `<article class="card${ratioClass}" id="card" style="${cardStyle(theme)}">${parts.join("")}</article>`;
}

function rebuildCard() {
  const old = $("#card");
  if (!old) return;
  old.outerHTML = buildCardHtml(currentData);
}

function renderResult(data) {
  currentData = data;
  // Initialise toggles: on by default, but only for fields that have data.
  for (const f of FIELD_DEFS) fieldOn[f.key] = f.has(data);

  const toggles = FIELD_DEFS.map((f) => {
    const available = f.has(data);
    return `<label class="fld ${available ? "" : "off"}">
      <input type="checkbox" data-field="${f.key}" ${fieldOn[f.key] ? "checked" : ""} ${available ? "" : "disabled"}>
      <span>${f.label}</span>
    </label>`;
  }).join("");

  return ensureFonts(activeTheme(data)).then(() => {
    stage.innerHTML = `
    <div class="fields">
      <span class="fields-title">Include</span>
      <label class="fld locked"><input type="checkbox" checked disabled><span>Title</span></label>
      ${toggles}
    </div>
    <div class="appearance" id="appearance">
      <span class="ctl"><label for="ctl-style">Style</label>
        <select id="ctl-style">
          <option value="journal" ${custom.style === "journal" ? "selected" : ""}>Journal</option>
          <option value="minimal" ${custom.style === "minimal" ? "selected" : ""}>Minimal</option>
        </select></span>
      <span class="ctl"><label for="ctl-scale">Font size</label>
        <input type="range" id="ctl-scale" min="75" max="145" step="5" value="${custom.scale}">
        <output id="out-scale">${custom.scale}%</output></span>
      <span class="ctl"><label for="ctl-width">Width</label>
        <input type="range" id="ctl-width" min="560" max="1000" step="20" value="${custom.width}">
        <output id="out-width">${custom.width}px</output></span>
      <span class="ctl"><label for="ctl-ratio">Ratio</label>
        <select id="ctl-ratio">
          ${[["auto", "Auto"], ["16/9", "16:9"], ["4/3", "4:3"], ["1/1", "1:1"], ["4/5", "4:5"]]
            .map(([v, t]) => `<option value="${v}" ${custom.ratio === v ? "selected" : ""}>${t}</option>`).join("")}
        </select></span>
      <span class="ctl"><label for="ctl-px">Export</label>
        <select id="ctl-px">
          ${[1, 2, 3].map((n) => `<option value="${n}" ${custom.pixelRatio === n ? "selected" : ""}>${n}×</option>`).join("")}
        </select></span>
    </div>
    ${buildCardHtml(data)}
    <p class="copynote" id="copynote"></p>
    <div class="actions">
      <button class="primary" id="copyimg">⧉ Copy image</button>
      <button id="png">⬇ Download PNG</button>
      <button id="cite">Copy citation</button>
      <button id="bibtex">Copy BibTeX</button>
      <button id="link">Copy link</button>
    </div>
  `;

    stage.querySelectorAll('.fields input[data-field]').forEach((cb) =>
      cb.addEventListener("change", () => {
        fieldOn[cb.dataset.field] = cb.checked;
        rebuildCard();
      })
    );

    const onCtl = (id, fn) => {
      const el = $(id);
      el.addEventListener("input", () => { fn(el); rebuildCard(); });
    };
    onCtl("#ctl-scale", (el) => {
      custom.scale = Number(el.value);
      $("#out-scale").textContent = `${custom.scale}%`;
    });
    onCtl("#ctl-width", (el) => {
      custom.width = Number(el.value);
      $("#out-width").textContent = `${custom.width}px`;
    });
    onCtl("#ctl-ratio", (el) => { custom.ratio = el.value; });
    onCtl("#ctl-px", (el) => { custom.pixelRatio = Number(el.value); });
    $("#ctl-style").addEventListener("input", (e) => {
      custom.style = e.target.value;
      ensureFonts(activeTheme(currentData)).then(rebuildCard);
    });

    $("#copyimg").addEventListener("click", (e) => copyCardImage(e.target));
    $("#png").addEventListener("click", downloadPng);
    $("#cite").addEventListener("click", (e) => copyText(e.target, citation(data)));
    $("#bibtex").addEventListener("click", (e) => copyText(e.target, bibtex(data)));
    $("#link").addEventListener("click", (e) =>
      copyText(e.target, `${location.origin}${location.pathname}?doi=${encodeURIComponent(data.doi)}`)
    );
  });
}

/* ---------- Exports ---------- */
async function downloadPng() {
  const card = $("#card");
  const btn = $("#png");
  const prev = btn.textContent;
  btn.textContent = "Rendering…";
  btn.disabled = true;
  try {
    if (currentData) await ensureFonts(activeTheme(currentData));
    const dataUrl = await htmlToImage.toPng(card, {
      pixelRatio: custom.pixelRatio,
      backgroundColor: "#ffffff",
      style: { boxShadow: "none" },
    });
    const a = document.createElement("a");
    a.download = `doishot-${slug($("#card").querySelector(".title").textContent)}.png`;
    a.href = dataUrl;
    a.click();
    btn.textContent = "✓ Saved";
  } catch (e) {
    btn.textContent = "Export failed";
  }
  btn.disabled = false;
  setTimeout(() => (btn.textContent = prev), 1600);
}

function slug(s) {
  return (s || "paper").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 50);
}

// Copy the rendered card to the clipboard as a PNG image.
async function copyCardImage(btn) {
  const card = $("#card");
  if (!card) return false;
  const prev = btn ? btn.textContent : "";
  if (btn) { btn.textContent = "Rendering…"; btn.disabled = true; }
  let ok = false;
  try {
    if (currentData) await ensureFonts(activeTheme(currentData));
    if (!navigator.clipboard || !window.ClipboardItem) throw new Error("no-clipboard-api");
    const blob = await htmlToImage.toBlob(card, {
      pixelRatio: custom.pixelRatio,
      backgroundColor: "#ffffff",
      style: { boxShadow: "none" },
    });
    await navigator.clipboard.write([new ClipboardItem({ "image/png": blob })]);
    ok = true;
  } catch (_) {
    ok = false;
  }
  if (btn) {
    btn.textContent = ok ? "✓ Copied" : "Press ⌘V failed - use Download";
    btn.classList.toggle("ok", ok);
    btn.disabled = false;
    setTimeout(() => { btn.textContent = prev; btn.classList.remove("ok"); }, ok ? 1500 : 2400);
  }
  return ok;
}

function citation(d) {
  const names = (d.authors || []).map(authorName).filter(Boolean);
  let auth = names.slice(0, 3).join(", ");
  if (names.length > 3) auth += ", et al.";
  const where = d.container || d.publisher || "";
  return `${auth}${auth ? " " : ""}(${d.year || "n.d."}). ${d.title}.${where ? " " + where + "." : ""} https://doi.org/${d.doi}`;
}

function bibtex(d) {
  const first = (d.authors || []).map(authorName).filter(Boolean)[0] || "anon";
  const key = (first.split(/[\s,]+/).pop() || "anon").toLowerCase() + (d.year || "");
  const authors = (d.authors || [])
    .map((a) => {
      const fam = a.family || a.familyName || "";
      const giv = a.given || a.givenName || "";
      return fam && giv ? `${fam}, ${giv}` : a.name || authorName(a);
    })
    .filter(Boolean)
    .join(" and ");
  const isArxiv = /^10\.48550\/arxiv/i.test(d.doi);
  const entry = isArxiv ? "misc" : "article";
  const lines = [
    `@${entry}{${key.replace(/[^a-z0-9]/gi, "")},`,
    `  title   = {${d.title}},`,
    authors && `  author  = {${authors}},`,
    d.container && `  journal = {${d.container}},`,
    d.year && `  year    = {${d.year}},`,
    d.publisher && !d.container && `  publisher = {${d.publisher}},`,
    `  doi     = {${d.doi}},`,
    `  url     = {https://doi.org/${d.doi}}`,
    `}`,
  ].filter(Boolean);
  return lines.join("\n");
}

async function copyText(btn, text) {
  try {
    await navigator.clipboard.writeText(text);
    const prev = btn.textContent;
    btn.textContent = "✓ Copied";
    btn.classList.add("ok");
    setTimeout(() => {
      btn.textContent = prev;
      btn.classList.remove("ok");
    }, 1500);
  } catch (_) {
    window.prompt("Copy:", text);
  }
}

/* ---------- Usage tracking ---------- */
const trackedDois = new Set();

function trackingConfig() {
  const c = window.__DOISHOT_CONFIG || {};
  const url = (c.SUPABASE_URL || "").replace(/\/+$/, "");
  const key = c.SUPABASE_ANON_KEY || "";
  if (!url || !key) return null;
  return { url, key };
}

function clipTelemetryField(value, maxLen) {
  if (value == null || value === "") return null;
  const s = String(value);
  return s.length <= maxLen ? s : s.slice(0, maxLen);
}

function trackShot({ doi, source }) {
  if (!doi || trackedDois.has(doi)) return;
  const cfg = trackingConfig();
  if (!cfg) return;
  trackedDois.add(doi);

  fetch(`${cfg.url}/rest/v1/usage_events`, {
    method: "POST",
    keepalive: true,
    headers: {
      "Content-Type": "application/json",
      apikey: cfg.key,
      Authorization: `Bearer ${cfg.key}`,
      Prefer: "return=minimal",
    },
    body: JSON.stringify({
      doi: clipTelemetryField(doi, 200),
      source: clipTelemetryField(source, 50),
      surface: "web",
    }),
  }).catch(() => {});
}

/* ---------- States ---------- */
function showLoading(doi) {
  stage.innerHTML = `<div class="status"><span class="spinner"></span>Resolving <b>${esc(doi)}</b>…</div>`;
}
function showError(msg) {
  stage.innerHTML = `<div class="status error">${esc(msg)}</div>`;
}

/* ---------- Flow ---------- */
async function run(rawValue, { push = true } = {}) {
  const doi = normalizeDoi(rawValue);
  if (!doi) {
    showError("That doesn't look like a DOI. Try e.g. 10.1038/nature12373 or arXiv:2303.08774");
    return;
  }
  input.value = doi;
  goBtn.disabled = true;
  showLoading(doi);
  if (push) {
    const u = new URL(location.href);
    u.searchParams.set("doi", doi);
    history.replaceState(null, "", u);
  }
  try {
    const data = await resolve(doi);
    await renderResult(data);
    trackShot({ doi: data.doi, source: data.source });
    // The "shot" is taken: drop the image straight onto the clipboard.
    const note = $("#copynote");
    const copied = await copyCardImage(null);
    if (note)
      note.textContent = copied
        ? "✓ Snapshot copied to clipboard - paste it anywhere (⌘V)."
        : "Snapshot ready - use Copy image or Download PNG below.";
  } catch (e) {
    showError("Couldn't find that DOI. Check it's correct - it may be unregistered or temporarily unavailable.");
  }
  goBtn.disabled = false;
}

