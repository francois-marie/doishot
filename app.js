/* ---------- DOI normalization ---------- */
// arXiv ids resolve to their DataCite-registered DOI (prefix 10.48550). The
// registered DOI is version-less, so we drop any trailing "v2".
function arxivToDoi(id) {
  return "10.48550/arXiv." + id.trim().replace(/\.pdf$/i, "").replace(/v\d+$/i, "");
}

// Accepts: raw DOIs, doi.org URLs, "doi:" prefixes, arXiv URLs/ids/bare ids,
// Nature article URLs, and most publisher URLs (which embed the DOI in the path).
function normalizeDoi(raw) {
  if (!raw) return null;
  let s = raw.trim();

  // --- arXiv ---
  const arxivUrl = s.match(/arxiv\.org\/(?:abs|pdf)\/([^\s?#]+)/i);
  if (arxivUrl) return arxivToDoi(arxivUrl[1]);
  const arxivPrefix = s.match(/^arxiv:\s*(.+)$/i);
  if (arxivPrefix) return arxivToDoi(arxivPrefix[1]);
  // bare new-style id (2303.08774, optional version), whole string only
  if (/^\d{4}\.\d{4,5}(v\d+)?$/i.test(s)) return arxivToDoi(s);
  // bare old-style id (hep-th/9901001), whole string only
  if (/^[a-z][a-z.-]+\/\d{7}(v\d+)?$/i.test(s)) return arxivToDoi(s);

  // --- Nature article URLs carry no DOI in the path: /articles/<id> -> 10.1038/<id> ---
  const nature = s.match(/nature\.com\/articles\/([a-z0-9-]+)/i);
  if (nature) return "10.1038/" + nature[1].replace(/\.pdf$/i, "");

  // --- Strip doi.org / doi: wrappers ---
  s = s.replace(/^https?:\/\/(dx\.)?doi\.org\//i, "");
  s = s.replace(/^doi:\s*/i, "");

  // --- Any embedded DOI: covers doi.org plus most publisher URLs
  // (APS, Science, Springer, Wiley, IOP, …) which put the DOI in the path. ---
  const m = s.match(/10\.\d{4,9}\/[^\s"'<>]+/);
  if (m) return decodeURIComponent(m[0]).replace(/[).,;]+$/, "");
  return null;
}

/* ---------- Helpers ---------- */
function stripTags(str) {
  if (!str) return "";
  const cleaned = str
    .replace(/<jats:title[^>]*>.*?<\/jats:title>/gi, "")
    .replace(/<\/?[^>]+>/g, " ");
  const doc = new DOMParser().parseFromString(cleaned, "text/html");
  return (doc.body.textContent || "").replace(/\s+/g, " ").trim();
}

function safeHttpUrl(url, fallback) {
  const s = String(url ?? "").trim();
  if (/^https?:\/\//i.test(s)) return s;
  return fallback;
}

function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])
  );
}

function authorName(a) {
  if (a.name) return a.name; // DataCite literal
  const given = a.given || a.givenName || "";
  const family = a.family || a.familyName || "";
  const full = `${given} ${family}`.trim();
  return full || a.literal || "";
}

function yearFromDateInput(partsOrIso) {
  if (!partsOrIso) return "";
  if (typeof partsOrIso === "string") {
    const m = partsOrIso.match(/^(\d{4})/);
    return m ? m[1] : "";
  }
  return partsOrIso[0] ? String(partsOrIso[0]) : "";
}

function formatPublicationDate(partsOrIso) {
  if (!partsOrIso) return "";
  let y = 0;
  let mo = 0;
  let d = 0;
  if (typeof partsOrIso === "string") {
    const m = partsOrIso.match(/^(\d{4})(?:-(\d{2})(?:-(\d{2}))?)?/);
    if (!m) return "";
    y = Number(m[1]);
    mo = m[2] ? Number(m[2]) : 0;
    d = m[3] ? Number(m[3]) : 0;
  } else {
    [y, mo, d] = partsOrIso;
    if (!y) return "";
  }
  if (mo && d) {
    return new Intl.DateTimeFormat("en-GB", {
      day: "numeric",
      month: "long",
      year: "numeric",
    }).format(new Date(Date.UTC(y, mo - 1, d)));
  }
  if (mo) {
    return new Intl.DateTimeFormat("en-GB", {
      month: "long",
      year: "numeric",
    }).format(new Date(Date.UTC(y, mo - 1, 1)));
  }
  return String(y);
}

function datePartsFromCrossref(m) {
  const fields = [m["published-online"], m["published-print"], m.issued];
  let best = null;
  for (const field of fields) {
    const parts = field && field["date-parts"];
    if (!parts || !parts[0] || !parts[0][0]) continue;
    if (!best || parts[0].length > best.length) best = parts[0];
  }
  return best;
}

function dateFromDataCite(a) {
  const preferred = (a.dates || []).find((entry) =>
    /^(issued|published|available|updated)$/i.test(entry.dateType || "")
  );
  if (preferred && preferred.date) return preferred.date;
  if (a.publicationYear) return String(a.publicationYear);
  return "";
}

function formatAuthors(authors) {
  const names = (authors || []).map(authorName).filter(Boolean);
  if (!names.length) return "";
  const CAP = 18;
  if (names.length <= CAP) return esc(names.join(", "));
  const shown = names.slice(0, CAP).join(", ");
  return `${esc(shown)} <span class="more">+ ${names.length - CAP} more</span>`;
}

/* ---------- Source resolvers ---------- */
async function fromCrossref(doi) {
  const r = await fetch(`https://api.crossref.org/works/${encodeURIComponent(doi)}`);
  if (!r.ok) throw new Error("crossref " + r.status);
  const m = (await r.json()).message;
  const dateParts = datePartsFromCrossref(m);
  return {
    source: "crossref",
    title: (m.title && m.title[0]) || "Untitled",
    authors: m.author || [],
    container: (m["container-title"] && m["container-title"][0]) || "",
    publisher: m.publisher || "",
    date: formatPublicationDate(dateParts),
    year: yearFromDateInput(dateParts),
    type: prettyType(m.type),
    abstract: stripTags(m.abstract),
    doi: m.DOI || doi,
    url: safeHttpUrl(m.URL, `https://doi.org/${doi}`),
  };
}

async function fromDataCite(doi) {
  const r = await fetch(`https://api.datacite.org/dois/${encodeURIComponent(doi)}`);
  if (!r.ok) throw new Error("datacite " + r.status);
  const a = (await r.json()).data.attributes;
  const abs = (a.descriptions || []).find(
    (d) => (d.descriptionType || "").toLowerCase() === "abstract"
  ) || (a.descriptions || [])[0];
  const dateRaw = dateFromDataCite(a);
  return {
    source: "datacite",
    title: (a.titles && a.titles[0] && a.titles[0].title) || "Untitled",
    authors: a.creators || [],
    container: (a.container && a.container.title) || "",
    publisher: a.publisher || "",
    date: formatPublicationDate(dateRaw),
    year: yearFromDateInput(dateRaw),
    type:
      prettyType(a.types && (a.types.resourceTypeGeneral || a.types.resourceType)) ||
      "Dataset",
    abstract: stripTags(abs && abs.description),
    doi: a.doi || doi,
    url: safeHttpUrl(a.url, `https://doi.org/${doi}`),
  };
}

function prettyType(t) {
  if (!t) return "";
  const map = {
    "journal-article": "Journal article",
    "posted-content": "Preprint",
    "proceedings-article": "Conference paper",
    "book-chapter": "Book chapter",
    Text: "Article",
    Preprint: "Preprint",
  };
  return map[t] || String(t).replace(/-/g, " ").replace(/^\w/, (c) => c.toUpperCase());
}

function uniq(list) {
  const seen = new Set();
  return list.filter((x) => x && !seen.has(x) && seen.add(x));
}

// Affiliations embedded in the registration-agency record (often sparse, and
// for arXiv's auto-generated DataCite deposits sometimes outright corrupt: a
// single stray string gets duplicated onto every creator regardless of their
// real affiliation, e.g. hundreds of authors all showing "Rai"). Detect that
// failure mode — one value covering nearly all of a large author list — and
// drop just that value rather than surface it as fact, keeping any genuine
// minority affiliations alongside it.
function affiliationsFrom(authors) {
  const out = [];
  for (const a of authors || [])
    for (const aff of a.affiliation || [])
      out.push(typeof aff === "string" ? aff : aff && aff.name);
  const filtered = out.filter(Boolean);
  if (filtered.length > 20) {
    const counts = new Map();
    for (const f of filtered) counts.set(f, (counts.get(f) || 0) + 1);
    const bogus = new Set();
    for (const [value, count] of counts)
      if (count / filtered.length > 0.9) bogus.add(value);
    if (bogus.size) return uniq(filtered.filter((f) => !bogus.has(f)));
  }
  return uniq(filtered);
}

// Many publishers (APS journals, Nature, …) don't deposit abstracts with
// Crossref, and affiliations are often missing too. OpenAlex has both (abstract
// as an inverted index, clean institution names) and is CORS-enabled. Free, no
// key. One call enriches both fields.
async function enrichFromOpenAlex(doi) {
  const empty = { abstract: "", affiliations: [], publicationDate: "" };
  try {
    const r = await fetch(
      `https://api.openalex.org/works/doi:${encodeURIComponent(doi)}` +
        `?select=abstract_inverted_index,authorships,publication_date`
    );
    if (!r.ok) return empty;
    const w = await r.json();
    let abstract = "";
    if (w.abstract_inverted_index) {
      const words = [];
      for (const [word, positions] of Object.entries(w.abstract_inverted_index))
        for (const i of positions) words[i] = word;
      abstract = words.join(" ").replace(/\s+/g, " ").trim();
    }
    const affiliations = uniq(
      (w.authorships || []).flatMap((au) =>
        (au.institutions || []).map((i) => i.display_name)
      )
    );
    return {
      abstract,
      affiliations,
      publicationDate: w.publication_date || "",
    };
  } catch (_) {
    return empty;
  }
}

async function resolve(doi) {
  // Enrich from OpenAlex in parallel; adds no latency in the common path, and
  // never throws (returns empties on failure).
  const enrichment = enrichFromOpenAlex(doi);
  let data;
  try {
    data = await fromCrossref(doi);
  } catch (_) {
    data = await fromDataCite(doi); // arXiv, datasets, software, etc.
  }
  const enr = await enrichment;
  // Prefer OpenAlex's clean institution names over the verbose / sparse
  // affiliation strings embedded in agency records; fall back to those.
  data.affiliations = enr.affiliations.length ? enr.affiliations : affiliationsFrom(data.authors);
  if (!data.abstract) data.abstract = enr.abstract;
  if (enr.publicationDate && (!data.date || /^\d{4}$/.test(data.date))) {
    data.date = formatPublicationDate(enr.publicationDate);
    data.year = yearFromDateInput(enr.publicationDate);
  }
  return data;
}

